#!/usr/bin/env node
// harvest-optimized-images.mjs — 把重建静态树（像素门的 REBUILD 侧）缺的 next/image 优化产物补齐
// （darkroom 实战入库，v0.3.13；rsc-reconstruction.md §3.5）。
// 为什么：镜像侧持有 Vercel 优化器的输出（w=1440 等变体），重建静态树没有优化器，serve.mjs 回落到
// 原图——两侧源分辨率不同，浏览器重采样差就是 0.2 级的像素残差。
// 做法：枚举静态树 HTML 里全部 `/_next/image?url=…&w=…&q=…`（src + srcset 全档），**镜像字节优先**
// （同 url+w+q，忽略 Vercel 的 dpl 部署 id——源站发了什么才是参照），镜像没有的档位才向本机
// `next start` 的优化器取（登记：这些档位是重建侧生成物），按 lib/urlpath 的查询变体命名落进静态树。
//   node tools/harvest-optimized-images.mjs [--base http://127.0.0.1:3311] [--site rebuild/static-site] [--mirror mirror]
import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import { join, dirname } from "node:path";
import { localRelPath, loadPolicy } from "../scripts/lib/urlpath.mjs";
import { readManifest } from "../scripts/lib/ledger.mjs";
import { cli } from "../scripts/lib/cli.mjs";
cli({ known: ["base", "site", "mirror"], file: import.meta.url });
const args = process.argv.slice(2);
const flag = (k, d) => { const i = args.indexOf("--" + k); return i >= 0 ? args[i + 1] : d; };
const BASE = flag("base", "http://127.0.0.1:3311"), SITE = flag("site", "rebuild/static-site"), MIRROR = flag("mirror", "mirror");
const POLICY = await loadPolicy(SITE);
async function* htmls(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isSymbolicLink()) continue;
    if (e.isDirectory()) yield* htmls(p); else if (e.name.endsWith(".html")) yield p;
  }
}
const urls = new Set();
for await (const f of htmls(SITE)) {
  const t = (await readFile(f, "utf8")).replace(/&amp;/g, "&");
  for (const m of t.matchAll(/\/_next\/image\?url=[^"'\s,]+/g)) urls.add(m[0]);
}
console.log(`optimized image refs: ${urls.size}`);
// 镜像账本必须在（lib/ledger.mjs：缺文件 -> null；坏文件 -> 抛）——没有账本就没有"镜像字节优先"可言。
const mf = await readManifest(MIRROR);
if (!mf) { console.error(`FATAL: no mirror-manifest.json under ${MIRROR}`); process.exit(1); }
const manifest = mf.files;
const mirrorByKey = new Map();
for (const [mu, e] of Object.entries(manifest)) {
  if (!mu.includes("/_next/image?") || !e.path) continue;
  const q = new URL(mu).searchParams;
  mirrorByKey.set(`${q.get("url")}|${q.get("w")}|${q.get("q")}`, e.path);
}
let ok = 0, fromMirror = 0, fail = 0;
for (const u of [...urls].sort()) {
  const q = new URL("http://x" + u).searchParams;
  const key = `${q.get("url")}|${q.get("w")}|${q.get("q")}`;
  let buf = null;
  if (mirrorByKey.has(key)) { buf = await readFile(join(MIRROR, mirrorByKey.get(key))); fromMirror++; }
  else {
    const r = await fetch(BASE + u).catch(() => null);
    if (!r || !r.ok) { fail++; console.log(`  FAIL ${r ? r.status : "net"} ${u.slice(0, 90)}`); continue; }
    buf = Buffer.from(await r.arrayBuffer());
  }
  const rel = localRelPath("http://x" + u, "x", POLICY);
  await mkdir(dirname(join(SITE, rel)), { recursive: true });
  await writeFile(join(SITE, rel), buf); ok++;
}
console.log(`saved ${ok} (from mirror ${fromMirror}, from local optimizer ${ok - fromMirror} — register these as rebuild-side generated bytes), failed ${fail}`);
process.exit(fail ? 1 : 0);
